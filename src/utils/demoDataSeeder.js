let isDemoActionInProgress = false;
const DEMO_LOCK_TIMEOUT_MS = 6000;

/**
 * Checks whether the demo action concurrency lock is currently active.
 * Used by ordinary task writes and cross-tab coordinators to detect active demo operations.
 *
 * @returns {boolean} True if lock is currently held
 */
export function isDemoLockActive(injectedStorage = null) {
  if (isDemoActionInProgress) return true;
  const storage = injectedStorage || (typeof window !== 'undefined' && window.localStorage ? window.localStorage : null);
  if (storage) {
    try {
      const existing = storage.getItem(DEMO_ACTION_LOCK_KEY);
      if (existing) {
        const lockTime = parseInt(existing, 10);
        if (!isNaN(lockTime) && Date.now() - lockTime < DEMO_LOCK_TIMEOUT_MS) {
          return true;
        }
      }
    } catch {
      // Storage unavailable
    }
  }
  return false;
}

/**
 * Attempts to acquire the demo action concurrency lock across callers and browser tabs.
 * Protects storage integrity against racing operations.
 * Auto-expires after 6 seconds to prevent deadlocks in case of tab crash or abnormal reload.
 *
 * @returns {boolean} True if lock was acquired
 */
export function acquireDemoLock() {
  if (isDemoLockActive()) {
    return false;
  }
  if (typeof window !== 'undefined' && window.localStorage) {
    try {
      window.localStorage.setItem(DEMO_ACTION_LOCK_KEY, String(Date.now()));
    } catch {
      // Storage unavailable; rely on in-memory flag
    }
  }
  isDemoActionInProgress = true;
  return true;
}

/**
 * Releases the demo action concurrency lock.
 */
export function releaseDemoLock() {
  isDemoActionInProgress = false;
  if (typeof window !== 'undefined' && window.localStorage) {
    try {
      window.localStorage.removeItem(DEMO_ACTION_LOCK_KEY);
    } catch {
      // Ignore
    }
  }
}

/**
 * Helper to safely rollback localStorage keys with read-back verification.
 * @param {string|null} preSeedTasksRaw
 * @param {string|null} preSeedActive
 * @param {string|null} preSeedSchedule
 */
function safeRollbackStorage(preSeedTasksRaw, preSeedActive, preSeedSchedule) {
  if (typeof window === 'undefined' || !window.localStorage) return;
  try {
    if (preSeedTasksRaw !== null) {
      window.localStorage.setItem(DEMO_STORAGE_TASKS_KEY, preSeedTasksRaw);
    } else {
      window.localStorage.removeItem(DEMO_STORAGE_TASKS_KEY);
    }
    if (preSeedActive !== null) {
      window.localStorage.setItem(DEMO_SEED_KEY, preSeedActive);
    } else {
      window.localStorage.removeItem(DEMO_SEED_KEY);
    }
    if (preSeedSchedule !== null) {
      window.localStorage.setItem(DEMO_STORAGE_ACCEPTED_SCHEDULE_KEY, preSeedSchedule);
    } else {
      window.localStorage.removeItem(DEMO_STORAGE_ACCEPTED_SCHEDULE_KEY);
    }
  } catch (err) {
    console.error('Storage rollback error:', err);
  }
}

/**
 * Persists tasks to localStorage with cross-tab conflict detection and coordination.
 * Protects against overwriting concurrent modifications from other tabs or active demo operations.
 *
 * @param {object[]} tasksToSave Array of tasks to persist
 * @param {object} [options={}]
 * @param {string} [options.expectedRevision] Optional revision previously loaded by the caller
 * @returns {{ success: boolean, conflict: boolean, reason?: string, tasks: object[], revision: string }}
 */
export function safePersistTasks(tasksToSave, options = {}) {
  if (typeof window === 'undefined' || !window.localStorage) {
    return { success: false, conflict: false, reason: 'storage_unavailable', tasks: tasksToSave, revision: '' };
  }

  // 1. Check if demo action lock is currently active
  if (isDemoLockActive()) {
    return {
      success: false,
      conflict: true,
      reason: 'demo_action_in_progress',
      tasks: tasksToSave,
      revision: window.localStorage.getItem(DEMO_STORAGE_REVISION_KEY) || '',
    };
  }

  // 2. Read current storage state to detect concurrent modifications
  const currentRaw = window.localStorage.getItem(DEMO_STORAGE_TASKS_KEY);
  const currentRevision = window.localStorage.getItem(DEMO_STORAGE_REVISION_KEY) || '';

  let finalTasks = tasksToSave;
  let hasConflict = false;

  if (currentRaw && options.expectedRevision && options.expectedRevision !== currentRevision) {
    hasConflict = true;
    try {
      const parsedCurrent = JSON.parse(currentRaw);
      if (Array.isArray(parsedCurrent)) {
        // Conflict resolution: Merge by task.id so non-overlapping edits and additions are preserved
        const taskMap = new Map();
        for (const t of parsedCurrent) {
          if (isValidTaskObject(t)) {
            taskMap.set(t.id, t);
          }
        }
        for (const t of tasksToSave) {
          if (isValidTaskObject(t)) {
            taskMap.set(t.id, t); // Local caller's newly saved/updated tasks take precedence
          }
        }
        finalTasks = Array.from(taskMap.values());
      }
    } catch {
      finalTasks = tasksToSave;
    }
  }

  const newRevision = `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
  try {
    window.localStorage.setItem(DEMO_STORAGE_TASKS_KEY, JSON.stringify(finalTasks));
    window.localStorage.setItem(DEMO_STORAGE_REVISION_KEY, newRevision);
    return { success: true, conflict: hasConflict, tasks: finalTasks, revision: newRevision };
  } catch (err) {
    return { success: false, conflict: false, reason: err.message, tasks: tasksToSave, revision: currentRevision };
  }
}

/**
 * Checks whether an interrupted demo reset left telemetry cleanup pending.
 * @returns {string|null} Profile ID for which cleanup is pending, or null
 */
export function getPendingDemoCleanupProfile() {
  if (typeof window === 'undefined' || !window.localStorage) return null;
  return window.localStorage.getItem(DEMO_CLEANUP_PENDING_KEY) || null;
}

/**
 * Retries pending telemetry cleanup idempotently.
 *
 * @param {Function} clearEventsFn Function to clear demo events in IndexedDB
 * @returns {Promise<{ success: boolean, cleaned: boolean, profileId: string|null }>}
 */
export async function resumePendingDemoCleanup(clearEventsFn) {
  const profileId = getPendingDemoCleanupProfile();
  if (!profileId || typeof clearEventsFn !== 'function') {
    return { success: true, cleaned: false, profileId: null };
  }
  try {
    const res = await clearEventsFn(profileId);
    if (res !== false) {
      window.localStorage.removeItem(DEMO_CLEANUP_PENDING_KEY);
      return { success: true, cleaned: true, profileId };
    }
    return { success: false, cleaned: false, profileId };
  } catch {
    return { success: false, cleaned: false, profileId };
  }
}

/**
 * Validates whether an object conforms to a minimal valid task shape.
 * @param {any} t
 * @returns {boolean}
 */
export function isValidTaskObject(t) {
  return Boolean(
    t &&
    typeof t === 'object' &&
    typeof t.id === 'string' &&
    t.id.trim().length > 0 &&
    typeof t.title === 'string' &&
    t.title.trim().length > 0
  );
}

/**
 * Checks whether a task is owned by the demo seeder.
 * Requires explicit provenance markers (isDemoSeed, isSyntheticData, provenanceSource).
 * Neither a canonical ID nor a matching title alone is sufficient proof of demo ownership,
 * as genuine user tasks may legitimately match canonical demo templates.
 * Unmarked records are never treated as demo-owned.
 *
 * @param {object} t Task object
 * @returns {boolean} True only if explicit demo provenance is present
 */
export function isDemoTask(t) {
  if (!t || typeof t !== 'object') return false;
  if (t.isDemoSeed === true || t.isSyntheticData === true || t.provenanceSource === 'demo_seeding_utility') {
    return true;
  }
  return false;
}

/**
 * Checks whether a task has an ambiguous demo-like ID or pattern without explicit demo provenance.
 * Ambiguous tasks are treated conservatively and preserved across reset operations.
 *
 * @param {object} t Task object
 * @returns {boolean} True if task matches demo conventions but lacks explicit provenance
 */
export function isAmbiguousDemoTask(t) {
  if (!t || typeof t !== 'object') return false;
  if (isDemoTask(t)) return false;
  if (typeof t.id === 'string' && (CANONICAL_DEMO_TASK_IDS.has(t.id) || /^demo-[ca]-[1-8]$/.test(t.id))) {
    return true;
  }
  return false;
}

/**
 * Safely parses and validates a backup payload.
 * Supports both versioned backup envelopes ({ schema_version, tasks, ... }) and legacy raw task arrays.
 * Hardened to reject unsupported schema versions, detect task count mismatches, and deduplicate IDs.
 *
 * @param {string} raw Raw JSON string from storage
 * @param {string|null} [activeProfileId=null] Optional active profile ID to detect profile mismatch
 * @returns {{ valid: boolean, tasks: object[], metadata: object, error?: string }}
 */
export function parseAndValidateBackup(raw, activeProfileId = null) {
  if (!raw || typeof raw !== 'string') {
    return { valid: false, tasks: [], metadata: {}, error: 'empty_backup' };
  }
  try {
    const parsed = JSON.parse(raw);
    let taskList = null;
    let metadata = {};

    if (Array.isArray(parsed)) {
      taskList = parsed;
      metadata = { format: 'legacy_array' };
    } else if (parsed && typeof parsed === 'object' && Array.isArray(parsed.tasks)) {
      const schemaVersion = Number(parsed.schema_version);
      if (schemaVersion && schemaVersion > 1) {
        return {
          valid: false,
          tasks: [],
          metadata: { schemaVersion },
          error: `unsupported_schema_version_${schemaVersion}`,
        };
      }
      taskList = parsed.tasks;
      metadata = {
        format: 'versioned_envelope',
        schemaVersion: schemaVersion || 1,
        backedUpAt: parsed.backed_up_at || null,
        profileId: parsed.profile_id || null,
        taskCount: typeof parsed.task_count === 'number' ? parsed.task_count : null,
      };

      if (typeof parsed.task_count === 'number' && parsed.task_count !== taskList.length) {
        return {
          valid: false,
          tasks: [],
          metadata,
          error: `task_count_mismatch: declared ${parsed.task_count}, found ${taskList.length}`,
        };
      }

      if (activeProfileId && parsed.profile_id && parsed.profile_id !== activeProfileId) {
        metadata.profileMismatch = true;
      }
    } else {
      return { valid: false, tasks: [], metadata: {}, error: 'unrecognized_structure' };
    }

    const seenIds = new Set();
    const validTasks = [];
    for (const t of taskList) {
      if (isValidTaskObject(t)) {
        if (!seenIds.has(t.id)) {
          seenIds.add(t.id);
          validTasks.push(t);
        }
      }
    }

    if (validTasks.length === 0 && taskList.length > 0) {
      return { valid: false, tasks: [], metadata, error: 'no_valid_tasks' };
    }

    return { valid: true, tasks: validTasks, metadata };
  } catch (err) {
    return { valid: false, tasks: [], metadata: {}, error: `json_parse_error: ${err.message}` };
  }
}

/**
 * Checks whether genuine user data is present in localStorage.
 * Distinguishes untouched initial welcome tasks or active demo tasks from genuine user modifications.
 *
 * @returns {boolean} True if user tasks or modifications exist
 */
export function hasExistingUserData() {
  if (typeof window === 'undefined' || !window.localStorage) {
    return false;
  }
  const raw = window.localStorage.getItem(DEMO_STORAGE_TASKS_KEY);
  if (!raw) return false;
  try {
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0) return false;
    // If all tasks are welcome tasks or demo tasks, it is considered fresh or active demo
    const isOnlyWelcomeOrDefault = parsed.every(
      (t) =>
        (typeof t.id === 'string' && t.id.startsWith('task-welcome-')) ||
        isDemoTask(t)
    );
    return !isOnlyWelcomeOrDefault;
  } catch {
    return true;
  }
}

